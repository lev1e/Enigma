def help_for(suffix: str) -> str:
    """Одна строка для пользователя: что сделать с файлом этого расширения."""
    return HELP.get(suffix.lower(), GENERIC)


# Файл с «текстовым» расширением, внутри которого двоичный контейнер: его нельзя разбирать как текст.
_DISGUISES = ((OLE_MAGIC, "старый двоичный документ Office"), (b"PK\x03\x04", "архив или документ ZIP"),
              (b"%PDF-", "PDF"), (b"{\\rtf", "RTF"), (b"\x89PNG", "картинка"), (b"\xff\xd8\xff", "картинка"))
MISMATCH = "Содержимое файла не соответствует расширению ({what}). Сохраните его в настоящем формате (.docx, .xlsx, .pptx, PDF) и загрузите снова."


def disguise(path) -> str:
    """Что на самом деле лежит в файле с текстовым расширением (пусто, если это обычный текст или файл не прочитать)."""
    try:
        with open(path, "rb") as fh:
            head = fh.read(8)
    except OSError:
        return ""
    for magic, what in _DISGUISES:
        if head.startswith(magic):
            return what
    return ""


def help_for_path(path) -> str:
    what = disguise(path)
    return MISMATCH.format(what=what) if what and path.suffix.lower() not in HELP else help_for(path.suffix)
